function setText(selector, value) {
	const element = document.querySelector(selector);

	if (element) {
		element.textContent = value;
	}
}

function setList(selector, values) {
	document.querySelectorAll(selector).forEach((element, index) => {
		if (values[index] !== undefined) {
			element.textContent = values[index];
		}
	});
}

function applyLanguage(language) {
	const t = translations[language] || translations.pl;

	document.documentElement.lang = t.lang;
	document.title = t.title;

	const metaDescription = document.querySelector('meta[name="description"]');
	if (metaDescription) {
		metaDescription.setAttribute("content", t.metaDescription);
	}

	const nav = document.querySelector(".navbar");
	if (nav) nav.setAttribute("aria-label", t.navAria);

	const navToggleButton = document.querySelector(".nav-toggle-button");
	if (navToggleButton) {
		navToggleButton.dataset.openLabel = t.openMenu;
		navToggleButton.dataset.closeLabel = t.closeMenu;
		navToggleButton.setAttribute("aria-label", navToggleButton.getAttribute("aria-expanded") === "true" ? t.closeMenu : t.openMenu);
	}

	const navControls = document.querySelector(".nav-controls");
	const languageSwitcher = document.querySelector(".language-switcher");
	const themeToggle = document.querySelector("#theme-toggle");
	if (navControls) navControls.setAttribute("aria-label", t.settings);
	if (languageSwitcher) {
		languageSwitcher.setAttribute("aria-label", t.languageSwitcher);
	}
	if (themeToggle) themeToggle.setAttribute("aria-label", t.themeSwitcher);

	setList(selectors.navLinks, t.nav);
	setText(selectors.heroTitle, t.heroTitle);
	setText(selectors.heroSubtitle, t.heroSubtitle);
	setText(selectors.heroText, t.heroText);
	setText(selectors.call, t.call);
	setText(selectors.emailButton, t.emailButton);

	document.querySelectorAll(selectors.serviceCards).forEach((card, index) => {
		const service = t.services[index];
		if (!service) return;

		const title = card.querySelector(".service-title h2");
		const text = card.querySelector(".service-description p");
		if (title) title.textContent = service.title;
		if (text) text.textContent = service.text;
	});

	setText(selectors.vehicleEyebrow, t.vehicleEyebrow);
	setText(selectors.vehicleTitle, t.vehicleTitle);
	document.querySelectorAll(selectors.specCards).forEach((card, index) => {
		const spec = t.specs[index];
		if (!spec) return;

		const label = card.querySelector("span");
		const value = card.querySelector("strong");
		if (label) label.textContent = spec.label;
		if (value) value.textContent = spec.value;
	});

	setText(selectors.areaEyebrow, t.areaEyebrow);
	setText(selectors.areaTitle, t.areaTitle);
	setText(selectors.areaText, t.areaText);
	setText(selectors.languagesEyebrow, t.languagesEyebrow);
	setList(selectors.languages, t.languages);
	setText(selectors.contactEyebrow, t.contactEyebrow);
	setText(selectors.contactTitle, t.contactTitle);
	setList(selectors.contactLabels, t.contactLabels);
	setText(selectors.locationEyebrow, t.locationEyebrow);
	setText(selectors.addressNote, t.addressNote);
	setText(selectors.footer, t.footer);
	setText(".gallery-eyebrow", t.galleryEyebrow);
	setText(".gallery-link-text", t.galleryLink);

	document.querySelectorAll(".photo-grid .gallery-tile").forEach((photo, index) => {
		photo.querySelector(".photo-caption").textContent = t.photoCaptions[index];
		document.querySelectorAll(`.gallery-tile[data-photo="${photo.dataset.photo}"]`).forEach((tile) => {
			tile.querySelector("img").alt = t.photoAlts[index];
			tile.setAttribute("aria-label", `${t.galleryOpen}: ${t.photoCaptions[index]}`);
		});
	});
	const modal = document.querySelector(".image-modal");
	if (modal) modal.setAttribute("aria-label", t.galleryLabel);
	document.querySelector(".image-modal-prev")?.setAttribute("aria-label", t.galleryPrevious);
	document.querySelector(".image-modal-next")?.setAttribute("aria-label", t.galleryNext);

	const backToTop = document.querySelector(selectors.backToTop);
	if (backToTop) {
		backToTop.setAttribute("aria-label", t.backToTop);
	}

	const modalClose = document.querySelector(".image-modal-close");
	if (modalClose) {
		modalClose.setAttribute("aria-label", t.galleryClose);
	}

	localStorage.setItem("site-language", language);
	document.dispatchEvent(new CustomEvent("languagechange", { detail: { language } }));
}

document.addEventListener("DOMContentLoaded", () => {
	const languageInputs = document.querySelectorAll(
		'.language-switcher input[name="language"]',
	);
	const savedLanguage = localStorage.getItem("site-language");
	const initialLanguage = translations[savedLanguage] ? savedLanguage : "pl";
	const initialInput = document.getElementById(`lang-${initialLanguage}`);

	if (initialInput) {
		initialInput.checked = true;
	}

	applyLanguage(initialLanguage);

	languageInputs.forEach((input) => {
		input.addEventListener("change", () => {
			if (input.checked) {
				applyLanguage(input.id.replace("lang-", ""));
			}
		});
	});
});
